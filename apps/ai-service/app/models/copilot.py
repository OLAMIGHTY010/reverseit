"""Pydantic schemas for AI Copilot Orchestration, Tool Calls, and Rule Suggestions.

Implements Prompt A7 requirements:
- Read-only tool definitions and invocation records
- Proposed action models (human must submit through gated API)
- Rule-improvement suggestion schemas with shadow simulation diffs
- Multi-turn conversation models scoped strictly to (case_id, user_id)
"""

from typing import Dict, List, Optional, Any
from pydantic import BaseModel, Field
import datetime
from app.models.context import CallerContext


class CopilotRole(str):
    USER = "user"
    ASSISTANT = "assistant"
    SYSTEM = "system"
    TOOL = "tool"


class CopilotMessage(BaseModel):
    role: str = Field(..., description="user, assistant, system, or tool")
    content: str
    timestamp: datetime.datetime = Field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc))
    cited_evidence_ids: List[str] = Field(default_factory=list)


class ProposedAction(BaseModel):
    """An action proposal generated by Copilot.
    
    IMPORTANT: Copilot NEVER executes actions. The human analyst must click or submit
    through the normal 8-check gated API.
    """
    model_config = {"protected_namespaces": ()}

    action_type: str = Field(..., description="e.g. PROPOSE_STATUS_QUERY, PROPOSE_APPROVAL_PACK, PROPOSE_ESCALATION")
    title: str
    description: str
    target_endpoint: str
    payload_preview: Dict[str, Any] = Field(default_factory=dict)
    requires_human_submission: bool = True
    requires_maker_checker: bool = True


class RuleImprovementProposal(BaseModel):
    """A proposed rule adjustment resulting from false positive/negative analysis."""
    model_config = {"protected_namespaces": ()}

    rule_id: str
    rule_name: str
    current_version: str
    proposed_version: str
    diff_summary: str
    rationale: str
    expected_impact: str
    shadow_simulation_results: Dict[str, Any] = Field(default_factory=dict)
    is_active: bool = False
    requires_risk_approval: bool = True


class CopilotChatRequest(BaseModel):
    model_config = {"protected_namespaces": ()}

    case_id: str
    session_id: str
    caller: CallerContext
    user_message: str
    history: List[CopilotMessage] = Field(default_factory=list)


class CopilotChatResponse(BaseModel):
    model_config = {"protected_namespaces": ()}

    case_id: str
    session_id: str
    response_text: str
    cited_evidence_ids: List[str] = Field(default_factory=list)
    tools_invoked: List[str] = Field(default_factory=list)
    proposed_actions: List[ProposedAction] = Field(default_factory=list)
    rule_suggestions: List[RuleImprovementProposal] = Field(default_factory=list)
    audit_ref: str
    is_refusal: bool = False
    refusal_reason: Optional[str] = None
